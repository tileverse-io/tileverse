package io.tileverse.vectortile.mvt;

/**
 * The geometry type of a feature, with the numbers of the {@code GeomType} enum of the vector tile schema.
 *
 * @see <a href="https://github.com/mapbox/vector-tile-spec/tree/master/2.1">Vector tile specification 2.1</a>
 */
enum GeomType {
    UNKNOWN(0),
    POINT(1),
    LINESTRING(2),
    POLYGON(3);

    private final int number;

    GeomType(int number) {
        this.number = number;
    }

    /** The number of the type in the tile bytes. */
    int number() {
        return number;
    }

    /**
     * Returns the type of a number, or null for a number outside the enum, as the enums generated by protobuf do. The
     * decoder keeps the previous type of a feature on such a number, as protobuf's parser does.
     */
    static GeomType forNumber(int number) {
        return switch (number) {
            case 0 -> UNKNOWN;
            case 1 -> POINT;
            case 2 -> LINESTRING;
            case 3 -> POLYGON;
            default -> null;
        };
    }
}
